#!/bin/bash
# Rewrites Sources/TrackerCore/Credits.swift from the repo's GitHub
# contributors. Run it when making a release: the app itself never asks
# GitHub for this, so Settings > About > Credits works offline and the app
# makes no extra network calls. Needs the GitHub CLI (`gh`).
set -euo pipefail
cd "$(dirname "$0")/.."

REPO="raymondtian30/claude-tracker"
ORIGINAL="BrodyKretz"  # the original creator: credited in their own section
OUT="Sources/TrackerCore/Credits.swift"

swift_string() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }

display_name() {
    gh api "users/$1" --jq '.name // ""'
}

entry() {  # login -> a Contributor(...) literal
    local name
    name="$(display_name "$1")"
    if [ -n "$name" ]; then
        printf 'Contributor(name: "%s", login: "%s")' "$(swift_string "$name")" "$1"
    else
        printf 'Contributor(name: nil, login: "%s")' "$1"
    fi
}

{
    echo "// Generated by scripts/update-credits.sh from GitHub's contributor list"
    echo "// for $REPO. Don't edit by hand: rerun the script."
    echo
    echo "/// Who made Claude Tracker, for Settings > About > Credits."
    echo "public enum Credits {"
    echo "    public struct Contributor: Equatable {"
    echo "        public let name: String?"
    echo "        public let login: String"
    echo "    }"
    echo
    echo "    public static let originalCreator = $(entry "$ORIGINAL")"
    echo
    echo "    /// Everyone else who has commits on GitHub, most commits first."
    echo "    public static let contributors: [Contributor] = ["
    gh api "repos/$REPO/contributors" --paginate --jq '.[] | select(.type == "User") | .login' |
        while read -r login; do
            [ "$login" = "$ORIGINAL" ] && continue
            echo "        $(entry "$login"),"
        done
    echo "    ]"
    echo "}"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "Wrote $OUT"
